from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
import numpy as np
import pandas as pd

def ts_evaluate(name, actual, pred):

    actual = pd.Series(actual).dropna()
    pred = pd.Series(pred).dropna()

    actual = actual.replace([np.inf, -np.inf], np.nan).dropna()
    pred = pred.replace([np.inf, -np.inf], np.nan).dropna()

    min_len = min(len(actual), len(pred))
    actual = actual.iloc[-min_len:]
    pred = pred.iloc[:min_len]

    if len(actual) == 0 or len(pred) == 0:
        print(f"\n{name} → Skipped (empty after cleaning)")
        return np.nan, np.nan

    rmse = np.sqrt(mean_squared_error(actual, pred))
    mae = mean_absolute_error(actual, pred)

    print(f"\n{name}")
    print(f"RMSE: {rmse:.4f}")
    print(f"MAE : {mae:.4f}")

    return rmse, mae

