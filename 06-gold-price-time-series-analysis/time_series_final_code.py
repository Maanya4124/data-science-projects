def ml_evaluate(name, y_true, y_pred):

    y_true = pd.Series(y_true).replace([np.inf, -np.inf], np.nan).dropna()
    y_pred = pd.Series(y_pred).replace([np.inf, -np.inf], np.nan).dropna()

    min_len = min(len(y_true), len(y_pred))
    y_true = y_true.iloc[:min_len]
    y_pred = y_pred.iloc[:min_len]

    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    mae = mean_absolute_error(y_true, y_pred)
    r2 = r2_score(y_true, y_pred)

    print(f"\n{name}")
    print(f"RMSE: {rmse:.4f}")
    print(f"MAE : {mae:.4f}")
    print(f"R2  : {r2:.4f}")

    return rmse, mae, r2


