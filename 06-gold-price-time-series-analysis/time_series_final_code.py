from statsmodels.stats.diagnostic import acorr_ljungbox

def residual_diagnostics(residuals, model_name):

    print(f"\nDiagnostics for {model_name}")

    residuals = residuals.dropna()

    # Residual plot
    plt.figure(figsize=(12,4))
    plt.plot(residuals)
    plt.title(f"{model_name} Residuals")
    pdf.savefig()
    plt.show()

    # Histogram
    plt.figure(figsize=(6,4))
    plt.hist(residuals, bins=30)
    plt.title(f"{model_name} Residual Histogram")
    pdf.savefig()
    plt.show()

    # ACF of residuals
    plot_acf(residuals, lags=40)
    plt.title(f"{model_name} Residual ACF")
    pdf.savefig()
    plt.show()

    # Ljung-Box test
    lb = acorr_ljungbox(residuals, lags=[10], return_df=True)
    print("Ljung-Box Test:")
    print(lb)

    if lb['lb_pvalue'].values[0] > 0.05:
        print("Residuals are WHITE NOISE")
    else:
        print("Residuals are NOT white noise")



